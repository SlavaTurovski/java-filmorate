--Таблица пользователей
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  login VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  birthday DATE NOT NULL
  );
COMMENT ON COLUMN users.id IS 'Идентификатор пользователя';
COMMENT ON COLUMN users.email IS 'Электронная почта';
COMMENT ON COLUMN users.login IS 'Логин пользователя';
COMMENT ON COLUMN users.name IS 'Имя пользователя';
COMMENT ON COLUMN users.birthday IS 'Дата рождения';

--Таблица дружбы пользователей
CREATE TABLE IF NOT EXISTS friendship (
  following_user_id INTEGER,
  followed_user_id INTEGER,
  friendship_status_id INTEGER,
  FOREIGN KEY (following_user_id) REFERENCES users(id),
  FOREIGN KEY (followed_user_id) REFERENCES users(id)
  );
COMMENT ON COLUMN friendship.following_user_id IS 'Пользователь';
COMMENT ON COLUMN friendship.followed_user_id IS 'Друг пользователя';
COMMENT ON COLUMN friendship.friendship_status_id IS 'Идентификатор статуса дружбы';

--Таблица возрастных рейтингов
CREATE TABLE IF NOT EXISTS mpa (
  mpa_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL
  );
COMMENT ON COLUMN mpa.mpa_id IS 'Идентификатор рейтинга';
COMMENT ON COLUMN mpa.name IS 'Название рейтинга';

--Таблица фильмов
CREATE TABLE IF NOT EXISTS films (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  release_date TIMESTAMP,
  duration INTEGER,
  mpa_id INTEGER,
  FOREIGN KEY (mpa_id) REFERENCES mpa(mpa_id)
  );
COMMENT ON COLUMN films.id IS 'Идентификатор фильма';
COMMENT ON COLUMN films.name IS 'Название фильма';
COMMENT ON COLUMN films.description IS 'Описание фильма';
COMMENT ON COLUMN films.release_date IS 'Дата выхода';
COMMENT ON COLUMN films.duration IS 'Продолжительность в минутах';
COMMENT ON COLUMN films.mpa_id IS 'Идентификатор возрастного рейтинга';

--Таблица жанров
CREATE TABLE IF NOT EXISTS genre (
  genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL
  );
COMMENT ON COLUMN genre.genre_id IS 'Идентификатор жанра';
COMMENT ON COLUMN genre.name IS 'Название жанра';

--Таблица фильмов и их принадлежности к жанру
CREATE TABLE IF NOT EXISTS film_genre (
  film_id INTEGER,
  genre_id INTEGER,
  FOREIGN KEY (film_id) REFERENCES films(id),
  FOREIGN KEY (genre_id) REFERENCES genre(genre_id)
  );
COMMENT ON COLUMN film_genre.film_id IS 'Идентификатор фильма';
COMMENT ON COLUMN film_genre.genre_id IS 'Идентификатор жанра';

--Таблица лайков фильмов
  CREATE TABLE IF NOT EXISTS film_likes (
      film_id INTEGER REFERENCES films(id) ON DELETE CASCADE,
      user_id INTEGER REFERENCES users(id)
  );
COMMENT ON COLUMN film_likes.film_id IS 'Идентификатор фильма';
COMMENT ON COLUMN film_likes.user_id IS 'Идентификатор пользователя';